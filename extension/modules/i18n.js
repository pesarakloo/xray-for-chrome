let language = "en";
export const getLanguage = () => language;
export const locale = () => language === "en" ? "en-US" : "fa-IR";
export const setLanguage = (value) => { language = value === "en" ? "en" : "fa"; };
export function t(source, values = {}) {
  const text = language === "en" ? (english[source] ?? source) : source;
  return text.replace(/\{(\w+)\}/g, (match, key) => String(values[key] ?? match));
}
export function localizeError(message) {
  const text = String(message || "خطای ناشناخته");
  if (language !== "en") return text;
  if (english[text]) return english[text];
  const patterns = [
    [/^خطای دریافت سابسکریپشن: HTTP (\d+)$/, (_, code) => `Subscription request failed: HTTP ${code}`],
    [/^ترنسپورت «(.*)» فعلاً پشتیبانی نمی‌شود\.$/, (_, value) => `Transport “${value}” is not supported.`],
    [/^امنیت «(.*)» پشتیبانی نمی‌شود\.$/, (_, value) => `Security mode “${value}” is not supported.`],
    [/^کانفیگ توسط Xray رد شد: ([\s\S]*)$/, (_, value) => `Xray rejected the configuration: ${value}`]
  ];
  for (const [pattern, replacement] of patterns) if (pattern.test(text)) return text.replace(pattern, replacement);
  return text; // Preserve third-party diagnostic details verbatim.
}
export function applyTranslations(root = document) {
  root.documentElement.lang = language;
  root.documentElement.dir = language === "en" ? "ltr" : "rtl";
  for (const node of root.querySelectorAll("[data-i18n]")) node.textContent = t(node.getAttribute("data-i18n"));
  for (const attr of ["placeholder", "aria-label", "title"]) {
    for (const node of root.querySelectorAll(`[data-i18n-${attr}]`)) node.setAttribute(attr, t(node.getAttribute(`data-i18n-${attr}`)));
  }
  const button = root.querySelector("#languageButton");
  if (button) {
    button.textContent = language === "fa" ? "English" : "فارسی";
    button.lang = language === "fa" ? "en" : "fa";
    button.setAttribute("aria-label", language === "fa" ? "Switch to English" : "تغییر زبان به فارسی");
    button.title = button.getAttribute("aria-label");
  }
}
